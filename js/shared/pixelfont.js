// A 5x7 pixel font on an 8-pixel grid, like the character ROMs of late-70s arcade boards.
// Each glyph is 7 rows; each row is a 5-bit number (16 = leftmost pixel).
(function () {
  'use strict';

  const G = {
    '0': [14, 17, 19, 21, 25, 17, 14], '1': [4, 12, 4, 4, 4, 4, 14], '2': [14, 17, 1, 2, 4, 8, 31],
    '3': [31, 2, 4, 2, 1, 17, 14], '4': [2, 6, 10, 18, 31, 2, 2], '5': [31, 16, 30, 1, 1, 17, 14],
    '6': [6, 8, 16, 30, 17, 17, 14], '7': [31, 1, 2, 4, 8, 8, 8], '8': [14, 17, 17, 14, 17, 17, 14],
    '9': [14, 17, 17, 15, 1, 2, 12],
    A: [14, 17, 17, 31, 17, 17, 17], B: [30, 17, 17, 30, 17, 17, 30], C: [14, 17, 16, 16, 16, 17, 14],
    D: [28, 18, 17, 17, 17, 18, 28], E: [31, 16, 16, 30, 16, 16, 31], F: [31, 16, 16, 30, 16, 16, 16],
    G: [14, 17, 16, 23, 17, 17, 15], H: [17, 17, 17, 31, 17, 17, 17], I: [14, 4, 4, 4, 4, 4, 14],
    J: [7, 2, 2, 2, 2, 18, 12], K: [17, 18, 20, 24, 20, 18, 17], L: [16, 16, 16, 16, 16, 16, 31],
    M: [17, 27, 21, 21, 17, 17, 17], N: [17, 17, 25, 21, 19, 17, 17], O: [14, 17, 17, 17, 17, 17, 14],
    P: [30, 17, 17, 30, 16, 16, 16], Q: [14, 17, 17, 17, 21, 18, 13], R: [30, 17, 17, 30, 20, 18, 17],
    S: [15, 16, 16, 14, 1, 1, 30], T: [31, 4, 4, 4, 4, 4, 4], U: [17, 17, 17, 17, 17, 17, 14],
    V: [17, 17, 17, 17, 17, 10, 4], W: [17, 17, 17, 21, 21, 21, 10], X: [17, 17, 10, 4, 10, 17, 17],
    Y: [17, 17, 17, 10, 4, 4, 4], Z: [31, 1, 2, 4, 8, 16, 31],
    '-': [0, 0, 0, 31, 0, 0, 0], '<': [2, 4, 8, 16, 8, 4, 2], '>': [8, 4, 2, 1, 2, 4, 8],
    '=': [0, 0, 31, 0, 31, 0, 0], '*': [0, 4, 21, 14, 21, 4, 0], '?': [14, 17, 1, 2, 4, 0, 4],
    '.': [0, 0, 0, 0, 0, 12, 12], '!': [4, 4, 4, 4, 4, 0, 4], ':': [0, 12, 12, 0, 12, 12, 0],
    '/': [1, 1, 2, 4, 8, 16, 16], "'": [4, 4, 8, 0, 0, 0, 0], ',': [0, 0, 0, 0, 12, 4, 8],
    '(': [2, 4, 8, 8, 8, 4, 2], ')': [8, 4, 2, 2, 2, 4, 8], '_': [0, 0, 0, 0, 0, 0, 31],
    '+': [0, 4, 4, 31, 4, 4, 0], '%': [24, 25, 2, 4, 8, 19, 3],
  };

  // Draws text using the context's current fillStyle.
  function draw(ctx, text, x, y, scale) {
    const s = scale || 1;
    const str = String(text).toUpperCase();
    for (let i = 0; i < str.length; i++) {
      const g = G[str[i]];
      if (!g) continue;
      const cx = x + i * 8 * s;
      for (let r = 0; r < 7; r++) {
        const bits = g[r];
        if (!bits) continue;
        for (let c = 0; c < 5; c++) {
          if (bits & (16 >> c)) ctx.fillRect(cx + c * s, y + r * s, s, s);
        }
      }
    }
  }

  function width(text, scale) {
    const s = scale || 1;
    return String(text).length * 8 * s - 3 * s;
  }

  function center(ctx, text, y, scale, screenWidth) {
    draw(ctx, text, Math.round((screenWidth - width(text, scale)) / 2), y, scale);
  }

  window.PixelFont = { draw, width, center };
})();
